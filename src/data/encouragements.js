// 날짜 기준으로 그날의 메시지 인덱스를 고정 선택(같은 날엔 동일).
export function pickEncouragement(list, dStr) {
  if (!list.length) return ''
  const d = new Date(dStr + 'T00:00:00')
  const epochDays = Math.floor(d.getTime() / 86400000)
  return list[epochDays % list.length]
}
